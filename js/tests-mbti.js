    MBTI_QUESTIONS.forEach(function (q, i) {
      var v = answers[i];
      if (v == null) v = 3;
      // вклад в сторону референсной буквы (E/N/T/P)
      sums[q.axis] += (q.pole5 === reference[q.axis]) ? v : (6 - v);
    });

